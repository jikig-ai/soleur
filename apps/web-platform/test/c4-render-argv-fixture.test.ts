// Sentinels the builder is fed; the fixture stores them as placeholders so the
// docker replay substitutes its own stage dir, node and likec4 entry. Stage is
// substituted first (it is the longest and unambiguous).
const SENTINELS = [
  { value: "/srv/c4-stage-root", placeholder: "{{STAGE}}" },
  { value: "/usr/local/lib/node_modules/likec4/bin/likec4.mjs", placeholder: "{{LIKEC4}}" },
  { value: "/usr/local/bin/node", placeholder: "{{NODE}}" },
] as const;

function project(tokens: readonly string[]): string[] {
  return tokens.map((t) => SENTINELS.reduce((acc, s) => acc.replaceAll(s.value, s.placeholder), t));
}

type C4Mod = typeof import("@/server/c4-render");

function sentinelInputs(m: C4Mod) {
  return {
    stageDir: SENTINELS[0].value,
    nodeBin: SENTINELS[2].value,
    extraRoBinds: [] as string[],
    command: m.renderCommand(SENTINELS[2].value, SENTINELS[1].value),
  };
}

/** The committed document, built from a bwrap-argv builder (the seam the
 *  mutation rows swap). Everything except the argv comes from production. */
function buildFixtureDoc(m: C4Mod, buildArgv: (o: ReturnType<typeof sentinelInputs>) => string[]) {
  const inputs = sentinelInputs(m);
  const launch = m.sandboxLaunch(inputs);
  const bwrapIdx = launch.args.indexOf(m.BWRAP_BIN);
  return {
    _comment:
      "Committed C4 render bwrap argv fixture (#10065 Guard 3). GENERATED by test/c4-render-argv-fixture.test.ts from buildLikeC4SandboxArgv + sandboxLaunch — never hand-edited; regenerate with: " +
      REGEN_CMD +
      ". The masked-/proc docker suite replays it (fd 9 = infra/bwrap-userns-clone3-deny.bpf, fd 3 = --json-status-fd) under docker's default masks; drift in the mount set is a reviewable diff, never silent. Placeholders: {{STAGE}} stage dir, {{NODE}} node binary, {{LIKEC4}} likec4 entry.",
    status: "generated",
    schema: "c4-render-bwrap-v1",
    launch: {
      cmd: launch.cmd,
      argsBeforeBwrap: project(launch.args.slice(0, bwrapIdx)),
    },
    bwrapBin: m.BWRAP_BIN,
    bwrapArgv: project(buildArgv(inputs)),
  };
}

function serialize(doc: unknown): string {
  return JSON.stringify(doc, null, 2) + "\n";
}

// ---- procfs-mount detection (pure; the rows below mutate argv through it) ----

const BIND_FLAGS = new Set(["--bind", "--bind-try", "--ro-bind", "--ro-bind-try", "--dev-bind", "--dev-bind-try"]);

function normPath(p: string): string {
  const n = path.posix.normalize(p.replace(/\/{2,}/g, "/"));
  return n.length > 1 ? n.replace(/\/+$/, "") : n;
}

/** Setup-argv tokens (before the `--` command separator) that mount, bind,
 *  link or name procfs: `--proc`, any token normalizing to /proc or under it,
 *  and a bind-family source of `/` (a recursive bind of the root carries the
 *  host's /proc mount in with it). */
function procfsMountTokens(argv: readonly string[]): string[] {
  const end = argv.indexOf("--");
  const setup = end === -1 ? argv : argv.slice(0, end);
  const hits: string[] = [];
  setup.forEach((tok, i) => {
    if (tok === "--proc") hits.push(`${i}:--proc`);
    else if (!tok.startsWith("--")) {
      const n = normPath(tok);
      if (n === "/proc" || n.startsWith("/proc/")) hits.push(`${i}:${tok}`);
    }
    if (BIND_FLAGS.has(tok) && setup[i + 1] !== undefined && normPath(setup[i + 1]) === "/") {
      hits.push(`${i + 1}:${setup[i + 1]} (bind of /)`);
    }
  });
  return hits;
}

/** Insert tokens right after `--seccomp 9`, where a stray `--proc` would sit. */
function withInserted(argv: string[], extra: string[]): string[] {
  const at = argv.indexOf("--seccomp") + 2;
  return [...argv.slice(0, at), ...extra, ...argv.slice(at)];
}

// ---- literal census ----

type Kinds = { BWRAP_BIN: number; BWRAP_PATH: number; literal: number; bare: number };
const ZERO: Kinds = { BWRAP_BIN: 0, BWRAP_PATH: 0, literal: 0, bare: 0 };

/** Code lines only. TS/JS comments come from the real TypeScript parser (the shared helper every source-walk guard
 *  uses, so `/* x *\/ spawn(BWRAP_BIN)` on one line is still seen and a `//` inside a string is not a comment);
 *  shell has no parser here, so a full-line `#` comment is dropped and a trailing one is left in (a miss there can
 *  only add a false RED, never hide a spawn site). */
function codeLines(src: string, ext: string): string[] {
  if (ext === ".sh") return src.split("\n").filter((l) => !/^\s*#/.test(l));
  return stripComments(src, `x${ext}`).split("\n");
}

function censusSource(src: string, ext: string): Kinds {
  const k = { ...ZERO };
  for (const line of codeLines(src, ext)) {
    k.BWRAP_BIN += (line.match(/\bBWRAP_BIN\b/g) ?? []).length;
    k.BWRAP_PATH += (line.match(/\bBWRAP_PATH\b/g) ?? []).length;
    k.literal += (line.match(/\/usr\/bin\/bwrap/g) ?? []).length;
    // Bare-name spawn target. Shell scripts invoke `bwrap` as a command word,
    // not a quoted literal, so only JS/TS count it.
    if (ext !== ".sh") k.bare += (line.match(/["'`]bwrap["'`]/g) ?? []).length;
  }
  return k;
}

const SCAN_EXT = new Set([".ts", ".tsx", ".js", ".mjs", ".cjs", ".sh"]);
const SKIP_DIRS = new Set(["node_modules", ".next", "dist", "coverage"]);

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (SCAN_EXT.has(path.extname(name))) out.push(full);
  }
  return out;
}

type Site = { role: "spawn" | "noise" | "operator-tool"; kinds: Partial<Kinds> };

/** Measured 2026-10-12 and pinned exactly. `spawn` = a production spawner that
 *  bypasses the shim (or, for sandbox-canary.mjs, replays both paths);
 *  `noise` = a bare "bwrap" literal that is not a spawn target (PATH lookup,
 *  shim-file name) — listed so a NEW literal anywhere is still a reviewed
 *  diff; `operator-tool` = a hand-run shell script naming the real binary.
 *  A third spawning file, a renamed export or a new use in an existing file
 *  reds the census: update this table in the same PR, deliberately. */
const EXPECTED_SITES: Record<string, Site> = {
  "server/agent-outer-wrap.ts": { role: "spawn", kinds: { BWRAP_PATH: 3, literal: 1 } },
  "server/c4-render.ts": { role: "spawn", kinds: { BWRAP_BIN: 3, literal: 1 } },
  "scripts/sandbox-canary.mjs": { role: "spawn", kinds: { literal: 2, bare: 4 } },
  "server/agent-runner-sandbox-config.ts": { role: "noise", kinds: { bare: 1 } },
  "scripts/plugin-root-sandbox-propagation-probe.mjs": { role: "noise", kinds: { bare: 1 } },
  "scripts/agent-outer-wrap-debug.sh": { role: "operator-tool", kinds: { BWRAP_PATH: 1, literal: 1 } },
  "scripts/bwrap-userns-seccomp-probe.sh": { role: "operator-tool", kinds: { literal: 1 } },
};
const SPAWN_FILES = Object.entries(EXPECTED_SITES).filter(([, s]) => s.role === "spawn");

function scanTree(root: string): Record<string, Kinds> {
  const found: Record<string, Kinds> = {};
  for (const dir of ["server", "scripts"]) {
    for (const file of walk(path.join(root, dir))) {
      const k = censusSource(readFileSync(file, "utf8"), path.extname(file));
      if (k.BWRAP_BIN + k.BWRAP_PATH + k.literal + k.bare > 0) {
        found[path.relative(root, file).split(path.sep).join("/")] = k;
      }
    }
  }
  return found;
}

/** Census verdict: [] when the found sites equal the expected table. */
function censusViolations(found: Record<string, Kinds>, expected: Record<string, Site>): string[] {
  const out: string[] = [];
  const spawnWant = Object.values(expected).filter((s) => s.role === "spawn").length;
  const spawnGot = Object.keys(found).filter((f) => expected[f]?.role === "spawn").length;
  if (Object.keys(found).length === 0 || spawnGot === 0) {
    out.push(`SPAWN_SITES want ${spawnWant} got ${spawnGot}`);
  }
  for (const f of Object.keys(found)) {
    if (!expected[f]) out.push(`unexpected bwrap site in ${f}: ${JSON.stringify(found[f])}`);
  }
  for (const [f, s] of Object.entries(expected)) {
    if (!found[f]) {
      out.push(`expected bwrap site missing: ${f} (${s.role})`);
      continue;
    }
    for (const key of Object.keys(ZERO) as (keyof Kinds)[]) {
      const want = s.kinds[key] ?? 0;
      if (found[f][key] !== want) out.push(`${f}: ${key} want ${want} got ${found[f][key]}`);
    }
  }
  return out;
}

/** Pull `export const NAME = "<literal>"` out of source text; null if absent
 *  (a renamed or un-exported constant). */
function exportedConstant(src: string, name: string): string | null {
  const m = new RegExp(`^export const ${name} = (["'\`])([^"'\`]*)\\1;`, "m").exec(src);
  return m ? m[2] : null;
}

function constantViolations(sources: { "c4-render.ts": string; "agent-outer-wrap.ts": string }): string[] {
  const out: string[] = [];
  const bin = exportedConstant(sources["c4-render.ts"], "BWRAP_BIN");
  if (bin !== "/usr/bin/bwrap") out.push(`BWRAP_BIN want "/usr/bin/bwrap" got ${JSON.stringify(bin)}`);
  const p = exportedConstant(sources["agent-outer-wrap.ts"], "BWRAP_PATH");
  if (p !== "/usr/bin/bwrap") out.push(`BWRAP_PATH want "/usr/bin/bwrap" got ${JSON.stringify(p)}`);
  return out;
}

