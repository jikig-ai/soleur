// Guard 3 (#10065) — the spawn paths that BYPASS the PATH bwrap shim.
//
// The shim (infra/bwrap-shim/bwrap) refuses procfs mounts; two production
// spawners deliberately run the real binary by absolute path instead: the C4
// render (`server/c4-render.ts`, BWRAP_BIN, nested in a bash launch argv) and
// the outer wrap (`server/agent-outer-wrap.ts`, BWRAP_PATH). Neither goes
// through the shim, so neither is protected by it — what keeps them correct
// under docker's default masked /proc is that their argv carries no procfs
// mount. This file pins that, statically:
//
//   1. the C4 argv, committed as infra/c4-render-sandbox-argv.json (a change
//      detector; the docker suite replays it under the masks),
//   2. a DIRECT no-procfs-mount assertion on the built argv (the pin alone
//      would pass a regenerated fixture that gained `--proc /proc`),
//   3. the OUTER-WRAP argv (the second shim-bypassing spawner), pinned to the builder by agent-outer-wrap.test.ts:
//      here, that it names exactly one /proc mount, the by-design `--bind /proc /proc`, and never `--proc`,
//   4. the two absolute-path constants, and
//   5. a LITERAL census of every bwrap spawn target in server/** and
//      scripts/** (never a "first spawn argument" scan: c4-render nests bwrap
//      in a bash argv, agent-outer-wrap has a spawn AND a spawnSync of
//      different shapes, sandbox-canary.mjs spawns both `bwrap` and
//      `/usr/bin/bwrap` — such a scan sees one site or passes vacuously).
//
// Regenerate the fixture (never hand-edit; refused when CI is set):
//   cd apps/web-platform && C4_ARGV_FIXTURE_REGEN=1 ./node_modules/.bin/vitest run test/c4-render-argv-fixture.test.ts
