describe("C4 render argv fixture pin (Guard 3)", () => {
  it("infra/c4-render-sandbox-argv.json equals the regenerated document", async () => {
    const m = await import("@/server/c4-render");
    const text = serialize(buildFixtureDoc(m, (o) => m.buildLikeC4SandboxArgv(o)));
    if (process.env.C4_ARGV_FIXTURE_REGEN === "1") {
      if (process.env.CI) throw new Error("C4_ARGV_FIXTURE_REGEN refuses to run when CI is set");
      writeFileSync(FIXTURE_PATH, text);
    }
    expect(
      readFileSync(FIXTURE_PATH, "utf8"),
      `c4-render-sandbox-argv.json drifted from buildLikeC4SandboxArgv. Review the diff, then regenerate: ${REGEN_CMD}`,
    ).toBe(text);
  });

  it("carries every placeholder and no sentinel path (a vacuous fixture would diff-equal)", async () => {
    const fx = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));
    expect(fx.schema).toBe("c4-render-bwrap-v1");
    expect(fx.status).toBe("generated");
    const all: string[] = [...fx.launch.argsBeforeBwrap, ...fx.bwrapArgv];
    for (const s of SENTINELS) {
      expect(all.some((t) => t.includes(s.placeholder)), `${s.placeholder} absent`).toBe(true);
      expect(all.filter((t) => t.includes(s.value)), `${s.value} leaked`).toEqual([]);
    }
    // The shape the replay relies on: the seccomp filter on fd 9, the status
    // record on fd 3, and a command after `--`.
    expect(fx.bwrapArgv.join(" ")).toContain("--seccomp 9");
    expect(fx.bwrapArgv.join(" ")).toContain("--json-status-fd 3");
    expect(fx.bwrapArgv.indexOf("--")).toBeGreaterThan(0);
    expect(fx.bwrapBin).toBe("/usr/bin/bwrap");
    expect(fx.launch.cmd).toBe("/usr/bin/bash");
  });

  it("the built argv carries no procfs mount (direct assertion, independent of the pin)", async () => {
    const m = await import("@/server/c4-render");
    const argv = m.buildLikeC4SandboxArgv(sentinelInputs(m));
    expect(procfsMountTokens(argv)).toEqual([]);
    expect(argv).not.toContain("--proc");
    // Instrument control: the detector is not vacuous on this argv.
    expect(procfsMountTokens(withInserted(argv, ["--proc", "/proc"])).length).toBeGreaterThan(0);
  });

  it("the committed fixture carries no procfs mount either", () => {
    const fx = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));
    expect(procfsMountTokens(fx.bwrapArgv)).toEqual([]);
  });
});

describe("mutation rows: a procfs mount is RED in both the pin and the direct assertion", () => {
  const MUTANTS: Array<[string, string[]]> = [
    ["--proc /proc", ["--proc", "/proc"]],
    ["--proc /proc/", ["--proc", "/proc/"]],
    ["--proc //proc", ["--proc", "//proc"]],
    ["--ro-bind /proc /proc", ["--ro-bind", "/proc", "/proc"]],
    ["--bind-try /proc /proc", ["--bind-try", "/proc", "/proc"]],
    ["--dev-bind /proc/ /x", ["--dev-bind", "/proc/", "/x"]],
    ["--ro-bind / /", ["--ro-bind", "/", "/"]],
  ];
  for (const [label, extra] of MUTANTS) {
    it(`${label}`, async () => {
      const m = await import("@/server/c4-render");
      const clean = serialize(buildFixtureDoc(m, (o) => m.buildLikeC4SandboxArgv(o)));
      const committed = readFileSync(FIXTURE_PATH, "utf8");
      const mutated = serialize(
        buildFixtureDoc(m, (o) => withInserted(m.buildLikeC4SandboxArgv(o), extra)),
      );
      expect(clean).toBe(committed); // must-pass control: the unmutated build is green
      expect(mutated).not.toBe(committed); // RED in the fixture pin
      expect(procfsMountTokens(withInserted(m.buildLikeC4SandboxArgv(sentinelInputs(m)), extra)).length)
        .toBeGreaterThan(0); // RED in the direct assertion
    });
  }

  it("a /proc path after the `--` command separator is not a mount (control)", () => {
    expect(procfsMountTokens(["--die-with-parent", "--", "/usr/bin/cat", "/proc/self/status"])).toEqual([]);
  });
});

describe("absolute-path constants and literal census (Guard 3)", () => {
  const SRC = {
    "c4-render.ts": readFileSync(path.join(APP_ROOT, "server", "c4-render.ts"), "utf8"),
    "agent-outer-wrap.ts": readFileSync(path.join(APP_ROOT, "server", "agent-outer-wrap.ts"), "utf8"),
  };

  it("BWRAP_BIN and BWRAP_PATH are the absolute /usr/bin/bwrap (the shim cannot intercept them)", async () => {
    const c4 = await import("@/server/c4-render");
    const ow = await import("@/server/agent-outer-wrap");
    expect(c4.BWRAP_BIN).toBe("/usr/bin/bwrap");
    expect(ow.BWRAP_PATH).toBe("/usr/bin/bwrap");
    expect(constantViolations(SRC)).toEqual([]);
  });

  it("BWRAP_BIN = \"bwrap\" (PATH-resolved, would go through the shim) is RED, constant pin and census", () => {
    const mutated = {
      ...SRC,
      "c4-render.ts": SRC["c4-render.ts"].replace(
        'export const BWRAP_BIN = "/usr/bin/bwrap";',
        'export const BWRAP_BIN = "bwrap";',
      ),
    };
    expect(mutated["c4-render.ts"]).not.toBe(SRC["c4-render.ts"]); // the mutation applied
    expect(constantViolations(mutated).join("\n")).toContain('BWRAP_BIN want "/usr/bin/bwrap" got "bwrap"');
    // The census sees it too: the literal count of c4-render.ts drops and a bare spawn target appears.
    const found = { ...scanTree(APP_ROOT), "server/c4-render.ts": censusSource(mutated["c4-render.ts"], ".ts") };
    const v = censusViolations(found, EXPECTED_SITES);
    expect(v).toContain("server/c4-render.ts: literal want 1 got 0");
    expect(v).toContain("server/c4-render.ts: bare want 0 got 1");
  });

  it("a renamed or un-exported constant is RED", () => {
    const renamed = SRC["c4-render.ts"].replace("export const BWRAP_BIN", "export const BWRAP_BINARY");
    expect(constantViolations({ ...SRC, "c4-render.ts": renamed })[0]).toContain('BWRAP_BIN want "/usr/bin/bwrap" got null');
    const unexported = SRC["agent-outer-wrap.ts"].replace("export const BWRAP_PATH", "const BWRAP_PATH");
    expect(constantViolations({ ...SRC, "agent-outer-wrap.ts": unexported })[0]).toContain("BWRAP_PATH want");
  });

  it("the census equals the pinned per-file table (measured sites, exactly)", () => {
    const found = scanTree(APP_ROOT);
    expect(censusViolations(found, EXPECTED_SITES), "update EXPECTED_SITES only after reviewing the new spawn path").toEqual([]);
    expect(SPAWN_FILES.map(([f]) => f).sort()).toEqual([
      "scripts/sandbox-canary.mjs",
      "server/agent-outer-wrap.ts",
      "server/c4-render.ts",
    ]);
  });

  it("a third spawning file is RED", () => {
    const found = { ...scanTree(APP_ROOT) };
    found["server/new-spawner.ts"] = censusSource(
      'import { spawn } from "node:child_process";\nspawn("/usr/bin/bwrap", ["--version"]);\n',
      ".ts",
    );
    expect(found["server/new-spawner.ts"].literal).toBe(1);
    expect(censusViolations(found, EXPECTED_SITES)).toContain(
      `unexpected bwrap site in server/new-spawner.ts: ${JSON.stringify(found["server/new-spawner.ts"])}`,
    );
    // A new use of a pinned constant in an existing file is RED too.
    const extra = { ...scanTree(APP_ROOT) };
    extra["server/c4-render.ts"] = censusSource(
      SRC["c4-render.ts"] + "\nspawn(BWRAP_BIN, []);\n",
      ".ts",
    );
    expect(censusViolations(extra, EXPECTED_SITES)).toContain("server/c4-render.ts: BWRAP_BIN want 3 got 4");
  });

  it("zero sites found (renamed export, moved tree) is RED with SPAWN_SITES want 3 got 0", () => {
    expect(censusViolations({}, EXPECTED_SITES)[0]).toBe("SPAWN_SITES want 3 got 0");
    // The real scan of a tree with empty server/ and scripts/ takes the same path.
    const empty = mkdtempSync(path.join(tmpdir(), "c4-census-"));
    mkdirSync(path.join(empty, "server"));
    mkdirSync(path.join(empty, "scripts"));
    try {
      expect(censusViolations(scanTree(empty), EXPECTED_SITES)[0]).toBe("SPAWN_SITES want 3 got 0");
    } finally {
      rmSync(empty, { recursive: true, force: true });
    }
  });

  it("the comment stripper ignores comment lines and trailing comments (control)", () => {
    const src = [
      '// "bwrap" and BWRAP_BIN in a comment',
      "/**",
      " * /usr/bin/bwrap in a doc block",
      " */",
      "const x = 1; // BWRAP_PATH trailing",
      'const y = "bwrap";',
      "/* note */ spawn(BWRAP_BIN, []);", // a comment earlier on the SAME line must not hide the spawn
      'const u = "http://x/usr/bin/bwrap";', // a // inside a string is not a comment
    ].join("\n");
    expect(censusSource(src, ".ts")).toEqual({ BWRAP_BIN: 1, BWRAP_PATH: 0, literal: 1, bare: 1 });
    expect(censusSource("# /usr/bin/bwrap\nexec /usr/bin/bwrap\n", ".sh").literal).toBe(1);
  });
});

describe("outer-wrap spawn path (the second shim-bypassing spawner)", () => {
  // agent-outer-wrap.test.ts pins this fixture to buildOuterWrapArgv; this file adds what that test does not
  // assert: the argv shares the host procfs by design (arm F, #9723 residual) through ONE bind, and a fresh
  // `--proc /proc` (the #9860 outage shape, refused under docker's default masks) is never added next to it.
  const OUTER_FIXTURE = path.join(APP_ROOT, "infra", "agent-outer-wrap-argv.json");
  const outerArgv = (): string[] => JSON.parse(readFileSync(OUTER_FIXTURE, "utf8")).bwrapSetupArgv;
  const INSERT_AT = 10;

  it("names exactly one procfs mount, the by-design `--bind /proc /proc`, and never --proc", () => {
    const argv = outerArgv();
    expect(argv.length).toBeGreaterThan(INSERT_AT);
    expect(argv).not.toContain("--proc");
    const hits = procfsMountTokens(argv);
    expect(hits).toHaveLength(2); // the source and destination token of the one bind
    const binds = argv.flatMap((t, i) => (t === "--bind" && argv[i + 1] === "/proc" ? [i] : []));
    expect(binds).toHaveLength(1);
    expect(argv.slice(binds[0], binds[0] + 3)).toEqual(["--bind", "/proc", "/proc"]);
  });

  for (const [label, extra] of [
    ["a fresh --proc /proc", ["--proc", "/proc"]],
    ["--proc //proc", ["--proc", "//proc"]],
    ["a second --bind /proc /proc", ["--bind", "/proc", "/proc"]],
    ["--ro-bind /proc /x", ["--ro-bind", "/proc", "/x"]],
  ] as Array<[string, string[]]>) {
    it(`the detector reds on ${label} added to the outer-wrap argv`, () => {
      const argv = outerArgv();
      const mutated = [...argv.slice(0, INSERT_AT), ...extra, ...argv.slice(INSERT_AT)];
      expect(procfsMountTokens(mutated).length).toBeGreaterThan(procfsMountTokens(argv).length);
    });
  }
});

