"""Offline wire-format experiment; output confers no authority or fencing.

This module has no transport or receipt-store integration. Validation proves
only that generated bytes match the local reservation shape contract.
"""
import importlib.util
import json
import re
from pathlib import Path

_spec = importlib.util.spec_from_file_location('holder_reservation_contract', Path(__file__).with_name('holder-reservation-contract.py'))
contract = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(contract)

_NUMERIC = ('epoch', 'vault_device', 'vault_inode', 'start_ms', 'deadline_ms')
_FIELDS = set(contract.COMMON) - {'version', 'purpose', 'entry'}


def _decimal(value):
    if type(value) is not int or not 0 <= value <= 2**64 - 1:
        raise ValueError('invalid reservation')
    return str(value)


def reserve(fields):
    if type(fields) is not dict or set(fields) != _FIELDS:
        raise ValueError('invalid reservation')
    for key in ('operation', 'generation', 'command', 'nonce', 'manifest_sha256',
                'controller_sha256', 'caller_sha256', 'audience_sha256'):
        value = fields[key]
        length = 64 if key.endswith('_sha256') else 32
        if type(value) is not str or len(value) != length or re.fullmatch(r'[0-9a-f]+', value) is None:
            raise ValueError('invalid reservation')
    values = dict(fields)
    for key in _NUMERIC:
        values[key] = _decimal(values[key])
    values.update(version='holder-reservation-v1', purpose='reserve', entry='receipt')
    raw = json.dumps({key: values[key] for key in contract.COMMON}, separators=(',', ':'), ensure_ascii=True)
    if contract.validate(raw) == 'unknown':
        raise ValueError('invalid reservation')
    return raw


def bind(reserve_raw, receipt_device, receipt_inode):
    if contract.validate(reserve_raw) == 'unknown':
        raise ValueError('invalid reservation')
    values = contract.parse(reserve_raw)
    values['purpose'] = 'bind'
    values['reserve_sha256'] = contract.digest(reserve_raw)
    values['receipt_device'] = _decimal(receipt_device)
    values['receipt_inode'] = _decimal(receipt_inode)
    raw = json.dumps(values, separators=(',', ':'), ensure_ascii=True)
    if contract.validate(raw, reserve_raw) == 'unknown':
        raise ValueError('invalid reservation')
    return raw
