/**
 * Location-bearing patterns on file tools that have no `path` parameter for them.
 *
 * `extractToolPath` (tool-path-checker.ts) only sees file_path / path / notebook_path, and both
 * hooks let an EMPTY path through ("defaults to the workspace"). Glob's `pattern` is a location
 * too: the bundled CLI treats a pattern that starts with a literal `/` as an absolute search root
 * and lets it win over `path`, so `/var/lib/soleur/egress-tokens/*` lists any directory in the
 * container with no `path` at all and never reaches isPathInWorkspace. The egress token dir is
 * bind-mounted into the container and a token FILE NAME there is a live gateway credential, so a
 * listing is the theft. `denyRead` only masks SANDBOXED BASH; these in-process tools run inside
 * the CLI process, and AGENT_OUTER_WRAP is off by default (agent-outer-wrap.ts).
 *
 * Grep's `glob` is only an rg `--glob` filter (its search root comes from `path`), so denying an
 * absolute one is defence in depth, not the escape. Grep's regex `pattern` is searched CONTENT,
 * not a location, and is deliberately NOT checked.
 *
 * Deny by SYNTAX, not by resolution (a glob has no single base directory): any alternative that is
 * absolute, starts with `~`, or is a bare `..` path segment escapes the workspace-relative contract.
 * Known-inert gaps (not worth a brace expander): a `..` generated by brace expansion (`.{.,}/x`)
 * and extglob/bracket forms; rg never matches `..` and the CLI only treats a LEADING `/` as absolute.
 * Same family: tool-path-checker.ts (#891, #725, #877).
 */

/** tool name -> the input field holding a glob (a location), not a content regex. Keys must be in FILE_TOOLS. */
const GLOB_FIELD: Readonly<Record<string, string>> = { Glob: "pattern", Grep: "glob" };

/** No legitimate glob is this long; failing closed also bounds the work on a pathological input. */
const MAX_GLOB_LENGTH = 4096;

export function patternEscapesWorkspace(
  toolName: string,
  toolInput: Record<string, unknown>,
): boolean {
  if (!Object.hasOwn(GLOB_FIELD, toolName)) return false;
  const value = toolInput?.[GLOB_FIELD[toolName]];
  if (typeof value !== "string" || value === "") return false;
  if (value.length > MAX_GLOB_LENGTH) return true;
  // Brace/comma/whitespace-separated alternatives are separate globs: `{src,/abs/dir}/*` names /abs/dir.
  for (const alt of value.split(/[\s{,]/)) {
    const g = alt.replace(/^!+/, "");
    if (g.startsWith("/") || g.startsWith("~")) return true;
    if (g.split(/[\\/]/).includes("..")) return true;
  }
  return false;
}
