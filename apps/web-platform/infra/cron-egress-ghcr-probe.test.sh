run_ghcr_probe 10000
check "hostile outputs: inconclusive, no event" "0" "$(ev_count)"
check "hostile outputs counted toward blind" "1" "$(counter ghcr.io)"
if [[ ! -e "$WORK/PWNED" ]]; then pass "dispatch executed nothing from hostile output"; else fail "dispatch created PWNED"; fi

echo "-- independent per-name state --"
new_state
mock_probe ghcr.io 127 ""; mock_probe docker.pkg.github.com 28 "$HELD"
run_ghcr_probe 10000
check "ghcr.io inconclusive counter" "1" "$(counter ghcr.io)"
check "docker.pkg.github.com held counter" "absent" "$(counter docker.pkg.github.com)"

# --- 4. sampler filter -----------------------------------------------------------------------
echo "-- filter_ghcr_probe_drops --"
assert_fixture_dir "$WORK"
cat > "$CIDR_FIXTURE" <<'CIDR_EOF'
# Container egress CIDR allowlist (synthesized fixture)
# Excluded (GitHub Packages frontends): 140.82.121.33/32
# Excluded (GitHub Packages frontends): 140.82.121.34/32
# Excluded (GitHub Packages frontends): 192.30.255.164/31
140.82.112.0/20
CIDR_EOF
kline() { # kline spt dpt dst [src]
  printf 'Oct  1 12:00:00 host kernel: egress-blocked: IN=docker0 OUT=eth0 SRC=%s DST=%s LEN=60 TOS=0x00 PROTO=TCP SPT=%s DPT=%s WINDOW=64240 SYN\n' "${4:-172.17.0.2}" "$3" "$1" "$2"
}
S_LABEL=(); S_LINE=(); S_WANT=()
sadd() { S_LABEL+=("$1"); S_LINE+=("$2"); S_WANT+=("$3"); }
sadd "probe SYN to carved /32 is dropped"                    "$(kline 49150 443 140.82.121.34)" drop
sadd "probe SYN to the other carved /32 is dropped"          "$(kline 49150 443 140.82.121.33)" drop
sadd "probe SYN to first address of the /31 is dropped"      "$(kline 49150 443 192.30.255.164)" drop
sadd "probe SYN to second address of the /31 is dropped"     "$(kline 49150 443 192.30.255.165)" drop
sadd "address after the /31 stays counted"                   "$(kline 49150 443 192.30.255.166)" keep
sadd "address before the /31 stays counted"                  "$(kline 49150 443 192.30.255.163)" keep
sadd "neighbour .32 of a carved /32 stays counted"           "$(kline 49150 443 140.82.121.32)" keep
