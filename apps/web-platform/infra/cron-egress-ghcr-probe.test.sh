table_verdict() { # table_verdict tag  -> runs every row; prints nothing but rows; sets ROWS_RUN
  ROWS_RUN=0
  local i got
  for i in "${!V_LABEL[@]}"; do
    ROWS_RUN=$((ROWS_RUN + 1))
    got="$(bash -euo pipefail -c 'source "$1"; ghcr_probe_verdict "$2" "$3"' _ "$LIB" "${V_RC[$i]}" "${V_RAW[$i]}" 2>/dev/null || echo "ABORTED-rc=$?")"
    check "${1}verdict: ${V_LABEL[$i]}" "${V_WANT[$i]}" "$got"
  done
}
table_verdict ""
check "verdict table instrument: every row ran" "${#V_LABEL[@]}" "$ROWS_RUN"
if [[ "$ROWS_RUN" -lt 32 ]]; then
  printf '[FATAL] verdict table: only %d rows ran, expected >= 32.\n' "$ROWS_RUN" >&2
  exit 1
fi
[[ ! -e "$WORK/PWNED" ]] && c=0 || c=1; okc "hostile output executed nothing (no PWNED file)" "$c"

