check "12th inconclusive run: one blind event per name (2)" "2" "$(ev_count ghcr_deny_probe_blind)"
reasons="$(awk -F'\t' '$1 == "ghcr_deny_probe_blind" { print $3 }' "$EVENTS" | jq -r .reason | sort -u | tr '\n' ',')"
check "blind reason is inconclusive" "inconclusive," "$reasons"
run_ghcr_probe "$now"; now=$((now + 300))
check "13th run: not re-emitted (exactly once at 12)" "2" "$(ev_count ghcr_deny_probe_blind)"
blind_msgs="$(awk -F'\t' '$1 == "ghcr_deny_probe_blind" { print $2 }' "$EVENTS" | sort -u | wc -l)"
check "blind message is one static literal" "1" "$blind_msgs"
if awk -F'\t' '$1 == "ghcr_deny_probe_blind" { print $2 }' "$EVENTS" | grep -qE '[$]|ghcr[.]io'; then fail "blind message not static"; else pass "blind message has no \$ / name"; fi
check "blind extra.last_rc" "127" "$(awk -F'\t' '$1 == "ghcr_deny_probe_blind" { print $3; exit }' "$EVENTS" | jq -r .last_rc)"
check "blind extra.name present" "ghcr.io" "$(awk -F'\t' '$1 == "ghcr_deny_probe_blind" { print $3; exit }' "$EVENTS" | jq -r .name)"

echo "-- blind: container absent x12 (counted skip, not silent) --"
new_state
CONTAINER_UP=0
now=10000
for i in $(seq 1 11); do run_ghcr_probe "$now"; now=$((now + 300)); done
check "11 absent runs: no blind event yet" "0" "$(ev_count ghcr_deny_probe_blind)"
run_ghcr_probe "$now"
check "12th absent run: blind event per name" "2" "$(ev_count ghcr_deny_probe_blind)"
check "absent runs never touch docker" "0" "$(docker_calls)"
check "blind reason is container_absent" "container_absent," "$(awk -F'\t' '$1 == "ghcr_deny_probe_blind" { print $3 }' "$EVENTS" | jq -r .reason | sort -u | tr '\n' ',')"
check "absent skip never emits lost" "0" "$(ev_count ghcr_deny_lost)"

echo "-- hostile probe output through dispatch --"
new_state
mock_probe ghcr.io 28 '0.012 a[$(touch '"$WORK"'/PWNED)] 1.2.3.4'
