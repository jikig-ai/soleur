#!/usr/bin/env bash
# Probe + sampler table for the GHCR deny probe in cron-egress-resolve.sh (#9275,
# ADR-096 5.3b-iii). Guard 2 of the plan's Guard Contract.
#
# NO LOGIC COPY: ghcr_probe_verdict / ghcr_probe_blind_step / run_ghcr_probe /
# filter_ghcr_probe_drops / ghcr_probe_filter_or_keep / strict_ipv4_lines and the
# GHCR_PROBE_* / CIDR_FILE assignments are extracted from the resolver by awk/grep on
# their definition lines and `source`d. Seams stubbed: the state dir (FAILCOUNT_DIR under
# a mktemp root), the clock (run_ghcr_probe's $1), sentry_event / container_running / log
# (recording functions), docker + nft (PATH shims that read canned output per probed
# name). Every table is driven by an array whose row count is floored, so a runner that
# iterates zero rows is RED, not green.
#
# Accounting: every verdict is recorded through check() or okc(), each of which bumps
# CASES at the call site before it records exactly one PASS or FAIL. The suite end asserts
# PASS + FAIL == CASES (a branch that records nothing, or a stray direct pass/fail call, is
# RED) and the helpers themselves are negative-controlled before any real row runs.
# shellcheck disable=SC2329,SC2016  # stubs are invoked via the sourced library; payloads are intentionally single-quoted
set -uo pipefail

export TMPDIR="${TMPDIR:-/var/tmp}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RESOLVER="${RESOLVER:-$SCRIPT_DIR/cron-egress-resolve.sh}"
COMMITTED_CIDR="$SCRIPT_DIR/cron-egress-allowlist-cidr.txt"

PASS=0
FAIL=0
CASES=0
pass() { PASS=$((PASS + 1)); echo "  PASS: $1"; }
fail() { FAIL=$((FAIL + 1)); echo "  FAIL: $1"; }
check() { # check "label" want got
  CASES=$((CASES + 1))
  if [[ "$2" == "$3" ]]; then pass "$1"; else fail "$1 (want='$2' got='$3')"; fi
}
okc() { # okc "label" <exit status of the test just run>  (0 = holds)
  CASES=$((CASES + 1))
  if [[ "$2" == "0" ]]; then pass "$1"; else fail "$1"; fi
}

assert_fixture_dir() {
  case "${1-}" in
    "") printf 'FATAL: fixture dir is EMPTY; git -C "" would operate on %s\n' "$PWD" >&2; exit 2 ;;
    */../*|*/..) printf 'FATAL: fixture dir %s contains ..; refusing\n' "$1" >&2; exit 2 ;;
    /proc/*|/sys/*|/dev/*) printf 'FATAL: fixture dir %s is a synthetic-fs path; refusing\n' "$1" >&2; exit 2 ;;
    /|//|/.) printf 'FATAL: fixture dir resolves to the filesystem root; refusing\n' >&2; exit 2 ;;
    /*) : ;;
    *)  printf 'FATAL: fixture dir %s is RELATIVE; refusing\n' "$1" >&2; exit 2 ;;
  esac
}

WORK="$(mktemp -d "${TMPDIR}/ghcr-probe-test.XXXXXX")"
assert_fixture_dir "$WORK"
cleanup() { assert_fixture_dir "$WORK"; rm -rf "$WORK"; }
trap cleanup EXIT

[[ -f "$RESOLVER" ]] || { echo "FATAL: resolver not found: $RESOLVER" >&2; exit 2; }

# --- negative control of the verdict-owning helpers -------------------------------------------
# Drive check() and okc() once with a MISMATCH and once with a match, redirected so the
# deliberate FAIL never reaches the transcript. FAIL must move for the mismatch and PASS for the
# match; then PASS/FAIL/CASES are unwound. Reported with printf + exit directly (never through
# check/fail): a helper that always passes would otherwise vouch for itself.
nc_p=$PASS; nc_f=$FAIL; nc_c=$CASES
check "negative-control mismatch" "want-A" "got-B" > "$WORK/nc1.out"
okc "negative-control failing condition" 1 > "$WORK/nc2.out"
check "negative-control match" "same" "same" > "$WORK/nc3.out"
okc "negative-control holding condition" 0 > "$WORK/nc4.out"
if (( FAIL - nc_f != 2 || PASS - nc_p != 2 || CASES - nc_c != 4 )) \
  || ! grep -q '^  FAIL: negative-control mismatch' "$WORK/nc1.out" \
  || ! grep -q '^  FAIL: negative-control failing condition' "$WORK/nc2.out" \
  || ! grep -q '^  PASS: negative-control match' "$WORK/nc3.out" \
  || ! grep -q '^  PASS: negative-control holding condition' "$WORK/nc4.out"; then
  printf '[FATAL] negative control: check()/okc() did not record the expected PASS/FAIL (dP=%d dF=%d dC=%d); the helpers cannot vouch for any row.\n' \
    "$((PASS - nc_p))" "$((FAIL - nc_f))" "$((CASES - nc_c))" >&2
  exit 1
fi
PASS=$nc_p; FAIL=$nc_f; CASES=$nc_c
echo "-- negative control: check()/okc() record a deliberate mismatch as FAIL (unwound) --"

# --- extraction (no logic copy) --------------------------------------------------------
extract_fn() { # extract_fn name  (definition line `name() {` through the closing `}` at col 0)
  awk -v n="$1" '
    $0 == n "() {" { p = 1 }
    p { print }
    p && $0 == "}" { exit }' "$RESOLVER"
}

CIDR_FIXTURE="$WORK/cidr.txt"
export CIDR_FILE="$CIDR_FIXTURE"
LIB="$WORK/probe-lib.sh"
LIB_FNS="ghcr_probe_verdict ghcr_probe_blind_step run_ghcr_probe filter_ghcr_probe_drops ghcr_probe_filter_or_keep strict_ipv4_lines"
assert_fixture_dir "$WORK"
{
  echo '# generated by cron-egress-ghcr-probe.test.sh from cron-egress-resolve.sh'
  grep -E '^GHCR_PROBE_[A-Z_]+=' "$RESOLVER"
  # The resolver's CIDR_FILE default is env-overridable; the test pre-exports CIDR_FILE.
  grep -E '^CIDR_FILE=' "$RESOLVER"
  for fn in $LIB_FNS; do
    extract_fn "$fn"
  done
} > "$LIB"

echo "-- extraction (non-vacuous) --"
EXTRACT_ROWS=0
for fn in $LIB_FNS; do
  EXTRACT_ROWS=$((EXTRACT_ROWS + 1))
  n="$(extract_fn "$fn" | wc -l)"
  [[ "$n" -ge 6 ]]; okc "extracted $fn ($n lines; expected >= 6)" $?
done
for c in GHCR_PROBE_PORT_LO GHCR_PROBE_PORT_HI GHCR_PROBE_INTERVAL GHCR_PROBE_BLIND_AT GHCR_PROBE_NAMES GHCR_PROBE_BUDGET_SECS; do
  EXTRACT_ROWS=$((EXTRACT_ROWS + 1))
  grep -qE "^$c=" "$LIB"; okc "constant $c extracted" $?
done
bash -n "$LIB"; okc "extracted library parses" $?
if [[ "$EXTRACT_ROWS" -lt 12 ]]; then
  printf '[FATAL] extraction table: only %d rows ran, expected >= 12.\n' "$EXTRACT_ROWS" >&2
  exit 1
fi

# --- stubs ------------------------------------------------------------------------------
MOCK="$WORK/mock"
SHIM="$WORK/shim"
EVENTS="$WORK/events.tsv"
LOGF="$WORK/log.txt"
FAILCOUNT_DIR="$WORK/state"
export FAILCOUNT_DIR
assert_fixture_dir "$WORK"
mkdir -p "$MOCK" "$SHIM" "$FAILCOUNT_DIR"

cat > "$SHIM/docker" <<'SHIM_EOF'
#!/usr/bin/env bash
echo "$*" >> "$MOCK_DIR/docker.args"
url="${*: -1}"; name="${url#https://}"; name="${name%/}"
if [[ -f "$MOCK_DIR/$name.out" ]]; then cat "$MOCK_DIR/$name.out"; fi
if [[ -f "$MOCK_DIR/$name.flood" ]]; then
  # 5 MB of junk after the real output. tr's status is 141 when the reader hung up early
  # (the cap held) and 0 when every byte was consumed (the cap is missing).
  head -c 5242880 /dev/zero | tr '\0' 'A'
  echo "${PIPESTATUS[1]}" > "$MOCK_DIR/$name.producer_rc"
fi
rc=0
if [[ -f "$MOCK_DIR/$name.rc" ]]; then rc="$(cat "$MOCK_DIR/$name.rc")"; fi
exit "$rc"
SHIM_EOF
cat > "$SHIM/nft" <<'SHIM_EOF'
#!/usr/bin/env bash
echo "$*" >> "$MOCK_DIR/nft.args"
rc=1
case "$*" in
  *soleur_egress_allow_cidr*) f="$MOCK_DIR/nft.cidr.rc" ;;
  *) f="$MOCK_DIR/nft.name.rc" ;;
esac
if [[ -f "$f" ]]; then rc="$(cat "$f")"; fi
exit "$rc"
SHIM_EOF
chmod +x "$SHIM/docker" "$SHIM/nft"
export MOCK_DIR="$MOCK"
export PATH="$SHIM:$PATH"

CONTAINER="soleur-web-platform"
CONTAINER_UP=1
CR_CALLS=0
log() { echo "$*" >> "$LOGF"; }
container_running() { CR_CALLS=$((CR_CALLS + 1)); [[ "$CONTAINER_UP" == "1" ]]; }
sentry_event() { # msg op extra  -> one TSV row: op, msg, compact extra ('' when extra is not JSON)
  local compact
  compact="$(jq -c . <<<"$3" 2>/dev/null || true)"
  printf '%s\t%s\t%s\n' "$2" "$1" "$compact" >> "$EVENTS"
}

# shellcheck disable=SC1090
source "$LIB"

new_state() { # fresh state dir, event log, mock outputs, docker/nft history
  assert_fixture_dir "$WORK"
  rm -rf "$FAILCOUNT_DIR" "$MOCK"
  mkdir -p "$FAILCOUNT_DIR" "$MOCK"
  : > "$EVENTS"
  : > "$LOGF"
  CONTAINER_UP=1
  CR_CALLS=0
  unset CRON_EGRESS_FROM_LOADER
  SECONDS=0
}
mock_probe() { # mock_probe name rc raw
  assert_fixture_dir "$WORK"
  printf '%s' "$3" > "$MOCK/$1.out"
  printf '%s' "$2" > "$MOCK/$1.rc"
}
mock_nft() { # mock_nft cidr_rc name_rc  (exit status of `nft get element` per set)
  printf '%s' "$1" > "$MOCK/nft.cidr.rc"
  printf '%s' "$2" > "$MOCK/nft.name.rc"
}
ev_count() { # ev_count [op]  (count of recorded events, optionally for one op)
  if [[ -n "${1:-}" ]]; then
    awk -F'\t' -v op="$1" '$1 == op { n++ } END { print n + 0 }' "$EVENTS"
  else
    awk 'END { print NR + 0 }' "$EVENTS"
  fi
}
docker_calls() { if [[ -f "$MOCK/docker.args" ]]; then wc -l < "$MOCK/docker.args"; else echo 0; fi; }
counter() { # counter name -> counter-file content ('absent' when missing)
  if [[ -f "$FAILCOUNT_DIR/ghcr_probe.$1.blind" ]]; then cat "$FAILCOUNT_DIR/ghcr_probe.$1.blind"; else echo absent; fi
}
stamp_of() { cat "$FAILCOUNT_DIR/ghcr_probe.stamp" 2>/dev/null || echo absent; }
blind_reasons() { awk -F'\t' '$1 == "ghcr_deny_probe_blind" { print $3 }' "$EVENTS" | jq -r .reason | sort -u | tr '\n' ','; }

