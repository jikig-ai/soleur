# shellcheck shell=bash
# Deterministic checks. Contract with launch-check.sh: TARGET, WORK, STACK, FACTS_OUT are set;
# $WORK/files lists the readable paths. Each check sets LC_STATUS (ok|gap|na|unsupported-stack) and
# LC_EVIDENCE (a path:line, a count, or a fixed phrase: never file content, never a secret location).
# File CONTENT is read in exactly one place, lc_grep_files.

# shellcheck disable=SC2034  # read by launch-check.sh flag parsing and SEC-01/SEC-02
LC_SHOW_SECRETS=0

lc_fact() { # <id> <status> <evidence>
  printf '%s\t%s\t%s\n' "$1" "$2" "$(lc_scrub "${3:--}")" >> "$FACTS_OUT"
}

# lc_glob_ere "a/*.yml|b": ERE alternation body (regex metacharacters escaped, * -> .*, ? -> .).
lc_glob_ere() {
  printf '%s' "$1" | sed -e 's/[][(){}.+^$\\]/\\&/g' -e 's/\*/.*/g' -e 's/?/./g'
}

# lc_match_files <globs> <outfile>: readable paths whose path, or any trailing path segment run, matches a glob.
lc_match_files() {
  local ere
  ere=$(lc_glob_ere "$1")
  RE="^(.*/)?($ere)\$" awk '$0 ~ ENVIRON["RE"]' "$WORK/files" > "$2"
}

# lc_grep_files <listfile> <ERE> [count]: the ONLY function that opens repo files for content.
# Prints the first "path:line" hit, or with "count" the total number of matches.
lc_grep_files() {
  if [ "${3:-}" = count ]; then
    tr '\n' '\0' < "$1" | (cd "$TARGET" && xargs -0 grep -IEo -e "$2" 2>/dev/null) | wc -l | tr -d ' '
  else
    tr '\n' '\0' < "$1" | (cd "$TARGET" && xargs -0 grep -IHnE -m1 -e "$2" 2>/dev/null) | head -n 1 | awk -F: 'NF>=2 {print $1 ":" $2}'
  fi
}

lc_check_presence() { # <glob> <regex> <expect>
  local glob=$1 regex=$2 expect=${3:-present} m="$WORK/match.list" hit
  lc_match_files "$glob" "$m"
  if [ ! -s "$m" ]; then
    hit=""
  elif [ "$regex" = "-" ]; then
    hit=$(head -n 1 "$m")
  else
    hit=$(lc_grep_files "$m" "$regex")
  fi
  if [ "$expect" = absent ]; then
    if [ -n "$hit" ]; then LC_STATUS=gap; LC_EVIDENCE="$hit"; else LC_STATUS=ok; LC_EVIDENCE="none found"; fi
  else
    if [ -n "$hit" ]; then LC_STATUS=ok; LC_EVIDENCE="$hit"; else LC_STATUS=gap; LC_EVIDENCE="not identified in the files read"; fi
  fi
}

# kind=guard rows are generated by baseline.sh: all emitted artifacts must exist in the target.
lc_check_guard() { # <semicolon-separated emitted paths> <semicolon-separated original source paths or ->
  local p missing="" srcmissing="" IFS=';'
  for p in $1; do [ -e "$TARGET/$p" ] || missing="${missing:+$missing, }$p"; done
  if [ -z "$missing" ]; then LC_STATUS=ok; LC_EVIDENCE="artifact present, advisory/unverified"; return; fi
  if [ "$2" != "-" ]; then
    for p in $2; do [ -e "$TARGET/$p" ] || srcmissing="$p"; done
    if [ -z "$srcmissing" ]; then LC_STATUS=ok; LC_EVIDENCE="original form present, advisory/unverified"; return; fi
  fi
  LC_STATUS=gap; LC_EVIDENCE="missing: $missing"
}

lc_detect_SEC_01() {
  local gl=${LAUNCH_CHECK_GITLEAKS:-gitleaks} arch="$WORK/arch" rep="$WORK/gl.json" rc=0 n f
  if ! git -C "$TARGET" rev-parse --verify -q HEAD >/dev/null 2>&1; then LC_STATUS=na; LC_EVIDENCE="no commits yet"; return; fi
  mkdir -p "$arch"
  git -C "$TARGET" archive --format=tar HEAD 2>/dev/null | tar -x -C "$arch" 2>/dev/null || true
  find "$arch" -type l -exec rm -f {} + 2>/dev/null || true
  while IFS= read -r f; do f=${f#./}; lc_safe_path "$f" || rm -f -- "${arch:?}/$f"; done < <(cd "$arch" && find . -type f)
  "$gl" detect --source "$arch" --no-git --report-format json --report-path "$rep" --redact --exit-code 1 >/dev/null 2>"$WORK/gl.err" || rc=$?
  if [ "$rc" -eq 0 ]; then LC_STATUS=ok; LC_EVIDENCE="none found"; return; fi
  if [ "$rc" -eq 1 ] && grep -q '"RuleID"' "$rep" 2>/dev/null; then
    n=$(grep -c '"RuleID"' "$rep")
    LC_STATUS=gap; LC_EVIDENCE="$n finding(s); locations withheld, run scan --show-secrets locally to see them"
    if [ "$LC_SHOW_SECRETS" = 1 ]; then
      grep -oE '"(File|StartLine)": *[^,]*' "$rep" | awk -v a="$arch/" '
        /"File"/ { f = $0; sub(/^[^:]*: *"/, "", f); sub(/"$/, "", f); if (index(f, a) == 1) f = substr(f, length(a) + 1); hf = 1 }
        /"StartLine"/ { l = $0; sub(/^[^:]*: */, "", l); hl = 1 }
        hf && hl { print "secret-location: " f ":" l; hf = 0; hl = 0 }'
    fi
    return
  fi
  lc_abort scanner-failed 2 "gitleaks rc=$rc"
}

lc_detect_SEC_02() {
  local n
  n=$(git -C "$TARGET" ls-files | awk '
    { b=$0; sub(".*/", "", b)
      if (b ~ /\.(example|sample|template|dist|pub)$/) next
      if (b ~ /^\.env($|\.)/ || b ~ /\.(key|p12|pfx|jks|tfvars)$/ || (b ~ /\.pem$/ && b ~ /(key|priv|secret)/) || b ~ /^(credentials|secrets)\./ || b ~ /^id_(rsa|dsa|ecdsa|ed25519)$/) c++ }
    END { print c+0 }')
  if [ "$n" -gt 0 ]; then
    LC_STATUS=gap; LC_EVIDENCE="$n file(s); names withheld, run scan --show-secrets locally to see them"
    if [ "$LC_SHOW_SECRETS" = 1 ]; then
      git -C "$TARGET" ls-files | awk '{ b=$0; sub(".*/", "", b); if (b !~ /\.(example|sample|template|dist|pub)$/ && (b ~ /^\.env($|\.)/ || b ~ /\.(key|p12|pfx|jks|tfvars)$/ || (b ~ /\.pem$/ && b ~ /(key|priv|secret)/) || b ~ /^(credentials|secrets)\./ || b ~ /^id_(rsa|dsa|ecdsa|ed25519)$/)) print "secret-location: " $0 }'
    fi
  else
    LC_STATUS=ok; LC_EVIDENCE="none found"
  fi
}

lc_detect_CI_02() {
  local t s
  read -r t s < <(awk '
    function istest(p) { return p ~ /(^|\/)(test|tests|__tests__|spec|specs)\// || p ~ /\.(test|spec)\.[A-Za-z0-9]+$/ || p ~ /(^|\/)test_[^\/]*\.py$/ || p ~ /_test\.(go|py|rb|exs)$/ || p ~ /Tests?\.(java|kt|cs)$/ }
    function issrc(p)  { return p ~ /\.(js|jsx|ts|tsx|mjs|cjs|py|rb|go|java|kt|rs|php|cs|swift|ex|exs)$/ }
    { if (issrc($0)) { if (istest($0)) t++; else s++ } }
    END { print t+0, s+0 }' "$WORK/files")
  if [ "$s" -eq 0 ] && [ "$t" -eq 0 ]; then LC_STATUS=na; LC_EVIDENCE="no source files recognized"
  elif [ "$t" -eq 0 ]; then LC_STATUS=gap; LC_EVIDENCE="0 test files / $s source files"
  elif [ "$s" -ge 20 ] && [ $((t * 20)) -lt "$s" ]; then LC_STATUS=gap; LC_EVIDENCE="$t test files / $s source files (under 5%)"
  else LC_STATUS=ok; LC_EVIDENCE="$t test files / $s source files"; fi
}

lc_detect_DEBT_01() {
  local n
  n=$(lc_grep_files "$WORK/files" '(^|[^A-Za-z0-9_])(TODO|FIXME|HACK|XXX|SOLEUR-DEBT)([^A-Za-z0-9_]|$)' count)
  if [ "${n:-0}" -ge 50 ]; then LC_STATUS=gap; else LC_STATUS=ok; fi
  LC_EVIDENCE="$n markers"
}

lc_detect_DEBT_05() {
  local pj="$WORK/pj.list"
  grep -E '(^|/)package\.json$' "$WORK/files" > "$pj" || true
  if [ ! -s "$pj" ]; then LC_STATUS=na; LC_EVIDENCE="no package.json"; return; fi
  if [ -z "$(lc_grep_files "$pj" '"next"[[:space:]]*:[[:space:]]*"')" ]; then LC_STATUS=na; LC_EVIDENCE="not a Next.js project"; return; fi
  if grep -qE '(^|/)\.?dependency-cruiser\.[a-z]+$' "$WORK/files" || [ -n "$(lc_grep_files "$pj" 'dependency-cruiser')" ]; then
    LC_STATUS=ok; LC_EVIDENCE="dependency-cruiser configured"
  else
    LC_STATUS=gap; LC_EVIDENCE="not identified in the files read"
  fi
}

# lc_run_checks <catalog> : append one fact row per non-judged check.
lc_run_checks() {
  # shellcheck disable=SC2034  # catalog columns are read positionally; not every cell is used here
  local cat=$1 id domain class kind title sev stacks glob regex expect closing remedy fn
  while IFS=$'\t' read -r id domain class kind title sev stacks glob regex expect closing remedy; do
    case "$id" in ''|'#'*|id) continue ;; esac
    [ "$kind" = judged ] && continue
    LC_STATUS=""; LC_EVIDENCE="-"
    if [ "$stacks" = node ] && [ "$STACK" != node ]; then
      lc_fact "$id" unsupported-stack "stack is $STACK"; continue
    fi
    case "$kind" in
      presence) lc_check_presence "$glob" "$regex" "$expect" ;;
      guard)    lc_check_guard "$glob" "$regex" ;;
      detector)
        fn="lc_detect_${id//-/_}"
        declare -F "$fn" >/dev/null || lc_abort catalog-detector-missing 2 "$id"
        "$fn" ;;
      *) lc_abort catalog-kind-unknown 2 "$id:$kind" ;;
    esac
    lc_fact "$id" "$LC_STATUS" "$LC_EVIDENCE"
  done < "$cat"
}
