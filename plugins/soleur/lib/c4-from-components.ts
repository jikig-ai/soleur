/**
 * True when the producer may write this path. `/soleur:architecture` writes
 * spec.c4 / model.c4 / views.c4 cwd-relative, and the agent sandbox pins
 * `cwd = workspacePath` — two writers, one directory. A tester who hand-corrects
 * a wrong edge must not have it silently reverted by the next sync.
 *
 * The header must be the FIRST line, not merely present somewhere in the body
 * (cq-assert-anchor-not-bare-token): a hand-authored file that happens to quote
 * the header in a comment is still a hand-authored file.
 */
export function canOverwrite(existing: string | null): boolean {
  if (existing === null) return true;
  return existing.split("\n", 1)[0].trim() === GENERATED_HEADER;
}

// ---------------------------------------------------------------------------
// generation
// ---------------------------------------------------------------------------

function escapeC4(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

/**
 * Emit the composing model file. Deterministic by construction: no timestamp, no
 * run id, sorted inputs — an unchanged component-doc set must produce a
 * byte-identical file, or every sync emits a diff forever.
 */
export function generateC4(components: ParsedComponent[], edges: Edge[]): string {
  const byName = new Map(components.map((c) => [c.name, c]));
  const out: string[] = [GENERATED_HEADER, "", "model {", ""];

  for (const c of components) {
    out.push(`  ${c.id} = component "${escapeC4(c.title)}" {`);
    out.push(`    description "${escapeC4(`Component: ${c.name}`)}"`);
    out.push("  }");
  }

  if (edges.length > 0) {
    out.push("");
    for (const e of edges) {
      const from = byName.get(e.from);
      const to = byName.get(e.to);
      if (!from || !to) continue;
      out.push(`  ${from.id} -> ${to.id} "depends on"`);
    }
  }

  out.push("}", "");
  return out.join("\n");
}

/**
 * Minimal `specification` block, emitted ONLY when the diagrams directory has no
 * other file declaring one. Without a `component` element kind, every generated
 * element is an unresolved reference and the whole render fails.
 */
export function generateSpecC4(): string {
  return [
    GENERATED_HEADER,
    "",
    "specification {",
    "  element component {",
    '    notation "Component"',
    "    style {",
    "      shape rectangle",
    "    }",
    "  }",
    "}",
    "",
  ].join("\n");
}

/** Minimal view so the model renders in the KB viewer. */
export function generateViewsC4(): string {
  return [
    GENERATED_HEADER,
    "",
    "views {",
    "  view generatedComponents {",
    '    title "Components (generated from knowledge base)"',
    "    include *",
    "  }",
    "}",
    "",
  ].join("\n");
}

/**
 * The markdown page carrying the view embed. The KB viewer renders a diagram only
 * for a markdown page with a `likec4-view` fence — three .c4 files alone are not
 * enough (api/kb/c4/project/route.ts also returns MODEL_NOT_BUILT without a
 * committed model.likec4.json).
 */
export function generateViewPage(viewId = "generatedComponents"): string {
  return [
    "# Components",
    "",
    "Generated by `/soleur:sync c4` from the component docs in",
    "`knowledge-base/project/components/`. Edges come from each doc's",
    "`dependencies:` frontmatter.",
    "",
    "```likec4-view",
    viewId,
    "```",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// validation
// ---------------------------------------------------------------------------

/**
 * Count elements and relationships in a rendered `model.likec4.json`.
 *
 * ‼️ The relationship key is `relations`, NOT `relationships`. Reading the wrong
 * key returns `undefined` -> 0, which makes `assessRender` report EVERY corpus as
 * degraded — a gate that always fires is exactly as useless as one that never
 * does, and no unit test over `assessRender` (which takes plain numbers) can see
 * it. `countModelJson` exists so the key mapping itself is pinned by a test
 * against a real likec4 artifact.
 *
 * Non-object shapes yield 0 rather than throwing: likec4 can emit a null/array
 * field, and a bare `Object.keys` on those would silently produce a wrong count.
 */
export function countModelJson(json: string): { elements: number; relationships: number } {
  try {
    const model = JSON.parse(json) as Record<string, unknown>;
    const size = (v: unknown) =>
      v && typeof v === "object" && !Array.isArray(v) ? Object.keys(v).length : 0;
    return { elements: size(model.elements), relationships: size(model.relations) };
  } catch {
    return { elements: 0, relationships: 0 };
  }
}

/**
 * The three gates. Order matters: a source fault is a hard failure regardless of
 * counts, an empty model is a failure, and only then is a zero-relationship model
 * classified — as `degraded`, never `failed`. The docs are the defect there, not
 * the run, and failing the sync over it would punish the tester for a corpus
 * Soleur itself taught them to write.
 */
export function assessRender(input: {
  diagnostics: string;
  elementCount: number;
  relationshipCount: number;
}): RenderVerdict {
  if (DIAG_RE.test(input.diagnostics)) {
    const line = input.diagnostics.split("\n").find((l) => DIAG_RE.test(l)) ?? "";
    return { status: "failed", reason: `likec4 reported a source fault: ${line.trim()}` };
  }
  if (input.elementCount === 0) {
    return { status: "failed", reason: "likec4 produced an empty/degenerate model" };
  }
  if (input.relationshipCount === 0) {
    return {
      status: "degraded",
      reason:
        "0 relationships — component docs declare no parseable dependencies, " +
        "so the diagram is a set of disconnected boxes",
    };
  }
  return { status: "ok" };
}
