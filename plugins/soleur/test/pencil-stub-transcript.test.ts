describe("stub replays the captured transcript", () => {
  const work = join(root, "replay");
  mkdirSync(join(work, "cwd"), { recursive: true });
  mkdirSync(join(work, "ro"), { recursive: true });
  writeFileSync(join(work, "garbage.pen"), "this is not a pen document\n");

  for (const session of transcript.sessions) {
    test(`session ${session.name}`, async () => {
      const norm = createNormalizer({ paths: [[work, "<WORK>"], [STUB_PKG_DIR, "<PEN>"]] });
      const args = session.args.map((a) => norm.unscrubArg(a));
      const env = session.noKey ? {} : KEY;
      const repl = new Repl(args, { env, cwd: join(work, "cwd") });
      const ready = await repl.settle();

      const startup = repl.take();
      norm.harvest(startup.out);
      expect(replyLines(norm.scrub(startup.out), { stripPrompt: true })).toEqual(session.startup.stdout);
      expect(replyLines(norm.scrub(startup.err), { stripPrompt: false })).toEqual(session.startup.stderr);
      if (!ready) {
        expect(session.steps.length).toBe(0);
        expect(repl.exited).toBe(session.exit);
        return;
      }

      for (const step of session.steps) {
        const cmd = norm.unscrubCommand(step.cmd);
        if (session.name === "readonly" && cmd === "save()") {
          if (process.getuid?.() === 0) writeFileSync(sideFile(join(work, "ro", "x.pen"), "flags"), JSON.stringify({ failSave: true }));
          else chmodSync(join(work, "ro"), 0o555);
        }
        const got = await repl.send(cmd);
        norm.harvest(got.out + "\n" + got.err);
        const stderr = replyLines(norm.scrub(got.err), { stripPrompt: false });
        const stdout = collapseReply(step.cmd, replyLines(norm.scrub(got.out), { stripPrompt: true }), stderr);
        expect({ cmd: step.cmd, stdout, stderr }).toEqual({ cmd: step.cmd, stdout: step.stdout, stderr: step.stderr });
      }
      expect(await repl.quit()).toBe(session.exit ?? 0);
    }, 60_000);
  }
});

