    expect(has(stdout, /^- Top-level nodes: /)).toBe(true);
    expect(has(stdout, /"mimeType": "image\/png"/)).toBe(true);
    expect(has(stdout, /^Exported <WORK>\/exports\//)).toBe(true);
    expect(has(stderr, /^Save failed: EACCES/)).toBe(true);
