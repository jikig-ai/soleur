// A small driver: one stub process, commands sent one at a time, stdout and stderr
// kept apart (the real engine puts every failure on stderr).

const ANSI = /\x1b\[[0-9;]*[a-zA-Z]/g;
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

class Repl {
  child: ChildProcess;
  out = "";
  err = "";
  exited: number | null = null;
  constructor(args: string[], opts: { env?: Record<string, string>; cwd?: string; bin?: string } = {}) {
    this.child = spawn(process.env.NODE_BIN || "node", [opts.bin ?? STUB, "interactive", ...args], {
      cwd: opts.cwd ?? root,
      env: { PATH: process.env.PATH ?? "", ...(opts.env ?? {}) },
      stdio: ["pipe", "pipe", "pipe"],
    });
    live.push(this.child);
    this.child.stdout!.on("data", (c) => (this.out += c.toString("utf8")));
    this.child.stderr!.on("data", (c) => (this.err += c.toString("utf8")));
    this.child.on("exit", (code) => (this.exited = code ?? -1));
  }
  /** Wait for the prompt at the END of stdout plus a quiet period, or for the process to exit. */
  async settle(timeoutMs = 15_000): Promise<boolean> {
    const t0 = Date.now();
    for (;;) {
      if (this.exited !== null) {
        await sleep(60);
        return false;
      }
      if (this.out.replace(ANSI, "").endsWith(REPL_PROMPT)) {
        const len = this.out.length;
        await sleep(80);
        if (this.out.length === len) return true;
      }
      if (Date.now() - t0 > timeoutMs) throw new Error(`timeout; stdout tail ${JSON.stringify(this.out.slice(-200))}`);
      await sleep(15);
    }
  }
  take() {
    const snap = { out: this.out, err: this.err };
    this.out = "";
    this.err = "";
    return snap;
  }
  async send(cmd: string) {
    this.child.stdin!.write(cmd + "\n");
    const ready = await this.settle();
    if (!ready) throw new Error(`stub exited during ${cmd.slice(0, 60)} (code ${this.exited}); stderr ${this.err.slice(-300)}`);
    return this.take();
  }
  async quit() {
    if (this.exited !== null) return this.exited;
    this.child.stdin!.write("exit()\n");
    const t0 = Date.now();
    while (this.exited === null && Date.now() - t0 < 5000) await sleep(20);
    return this.exited;
  }
}

