    pass "$1"
  else
    fail "$1: expected exactly one finding at line $3 with step label '${4:-<unnamed>}', got: $(head -c 300 "$WORK/err")"
  fi
}
yline_mut_row() { # <label> <perl-expr> <fixture basename> <line> <step name>: the pinned row must read RED on the mutant
