      ORC_WANT=1
    elif [ "$n_depr" -ge 1 ]; then
      ORC_CLASS="cut"
    else
      ORC_CLASS=neg
      ORC_WANT=0
    fi
  elif [ "$ORC_RC" = "0" ]; then
    ORC_CLASS=terminal
  else
    ORC_CLASS=rejected
    ORC_WANT=0
  fi
  if [ "$ORC_CLASS" = "cut" ] || [ "$ORC_CLASS" = "terminal" ]; then
    help="$(orc_help_noarg "${first:1:1}")"
    if [ "$help" = "noarg" ]; then ORC_WANT=1; else ORC_WANT=0; fi
  fi
}
